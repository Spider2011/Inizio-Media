// Builds the Our Work gallery from the source images in /images (not committed).
// Each image is resized to at most 1080px wide, saved as WebP in public/work/gallery/, and listed
// with its size in src/data/gallery.ts. Posts from the same account are mixed through the gallery
// so no client's images sit in a clump. Run with `npm run gallery` after adding or removing images.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = path.join(ROOT, 'images');
const OUT_DIR = path.join(ROOT, 'public', 'work', 'gallery');
const DATA_FILE = path.join(ROOT, 'src', 'data', 'gallery.ts');
const MAX_WIDTH = 1080;
const QUALITY = 80;
/* Not client work: the studio's own logo. */
const SKIP = new Set(['Full Colour.png']);
/* Shown in the gallery's second row on every screen size (the rest keep their mixed order). */
const SECOND_ROW = new Set(['O & B Logo W.png']);
const IMAGE = /\.(jpe?g|png|webp)$/i;

/** Which account a file came from: Instagram media ids end with a fragment of the account id;
    other files group by their name's first word. */
export function accountOf(file) {
  const id = /_(\d{12,})_/.exec(file);
  if (id) return id[1].slice(-6);
  return file.replace(/[-_ .\d].*$/, '').toLowerCase() || file;
}

/** Deals the files out one account at a time, round-robin, keeping each account's own order. */
export function interleave(files) {
  const groups = new Map();
  for (const file of files) {
    const key = accountOf(file);
    groups.set(key, [...(groups.get(key) ?? []), file]);
  }
  const queues = [...groups.values()];
  const out = [];
  while (out.length < files.length) {
    for (const queue of queues) if (queue.length) out.push(queue.shift());
  }
  return out;
}

async function build() {
  if (!fs.existsSync(SOURCE)) throw new Error(`No source folder at ${SOURCE}`);
  const files = interleave(fs.readdirSync(SOURCE).filter((f) => IMAGE.test(f) && !SKIP.has(f)).sort());
  fs.rmSync(OUT_DIR, { recursive: true, force: true });
  fs.mkdirSync(OUT_DIR, { recursive: true });

  const entries = [];
  for (const [i, file] of files.entries()) {
    const name = `${String(i + 1).padStart(2, '0')}.webp`;
    const image = sharp(path.join(SOURCE, file)).rotate();
    const { isOpaque } = await image.stats();
    const info = await image
      .resize({ width: MAX_WIDTH, withoutEnlargement: true })
      .webp({ quality: QUALITY, alphaQuality: 90 })
      .toFile(path.join(OUT_DIR, name));
    entries.push({ src: `/work/gallery/${name}`, width: info.width, height: info.height, transparent: !isOpaque, secondRow: SECOND_ROW.has(file) });
  }

  const lines = entries.map(
    (e) => `  { src: '${e.src}', width: ${e.width}, height: ${e.height}${e.transparent ? ', transparent: true' : ''}${e.secondRow ? ', secondRow: true' : ''} }`
  );
  fs.writeFileSync(
    DATA_FILE,
    [
      '/* GENERATED by scripts/build-gallery.mjs from /images. Do not edit by hand: run `npm run gallery`. */',
      '',
      'export type GalleryImage = {',
      '  src: string;',
      '  width: number;',
      '  height: number;',
      '  /** Has see-through areas (a logo file): shown on a dark tile so white parts stay visible. */',
      '  transparent?: boolean;',
      '  /** Placed in the second row whatever the column count. */',
      '  secondRow?: boolean;',
      '};',
      '',
      'export const GALLERY: readonly GalleryImage[] = [',
      lines.join(',\n'),
      '];',
      ''
    ].join('\n')
  );
  const kb = fs.readdirSync(OUT_DIR).reduce((sum, f) => sum + fs.statSync(path.join(OUT_DIR, f)).size, 0) / 1024;
  console.log(`${entries.length} images → public/work/gallery (${Math.round(kb)} KB), src/data/gallery.ts`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  await build();
}
